import tkinter as tk  # Імпортуємо бібліотеку tkinter для створення графічного інтерфейсу

# Створюємо головне вікно програми
window = tk.Tk()  # Створюємо об'єкт головного вікна
window.title("Текстове поле")  # Встановлюємо заголовок вікна
window.geometry("400x200")  # Встановлюємо розмір вікна (ширина x висота)

# Функція, що виконується при натисканні кнопки
def on_click():
    text = entry.get()  # Отримуємо текст, який користувач ввів у поле
    label.config(text=f"Ви ввели: {text}")  # Змінюємо напис, щоб показати введений текст

# Створюємо напис (Label)
label = tk.Label(
    window,                 # У якому вікні розміщено
    text="Введіть щось у поле нижче:",  # Початковий текст
    font=("Arial", 14)      # Шрифт і розмір
)
label.pack(pady=10)  # Додаємо елемент у вікно з відступом

# Створюємо текстове поле (Entry)
entry = tk.Entry(
    window,          # Вікно, де розміщуємо поле
    font=("Arial", 14),  # Шрифт тексту в полі
    width=25         # Ширина поля (кількість символів)
)
entry.pack(pady=5)  # Додаємо у вікно з невеликим відступом

# Створюємо кнопку
button = tk.Button(
    window,              # Вікно, де розміщуємо кнопку
    text="Показати текст",  # Текст на кнопці
    font=("Arial", 12),  # Шрифт
    command=on_click     # Вказуємо, яку функцію викликати при натисканні
)
button.pack(pady=10)  # Додаємо кнопку у вікно

# Запускаємо головний цикл (щоб вікно залишалось відкритим)
window.mainloop()